export const THEME_VERSION = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
/** What a build may write into the output directory, from each output's owner (the bridge and share.json names are @descix/app-sdk's). */
export async function pageOutputs(fromDir) {
  return Object.freeze([PAGE_FILE, `${IMAGES_OUT}/`, (await loadBridgeFile(fromDir)).name, (await loadShareContract(fromDir)).SHARE_JSON_FILE]);
}
export const STILLS_DIR = 'exhibits';
/** The app's import-map block: two marker lines its own generator fills (scripts.import_map). */
export const IMPORT_MAP_BEGIN = '<!-- IMPORT-MAP:BEGIN generated by scripts/gen-import-maps.mjs from site/vendor/frqtl-web/PINNED.json -->';
export const IMPORT_MAP_END = '<!-- IMPORT-MAP:END -->';

const git = (cwd, ...a) => execFileSync('git', a, { cwd, maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'pipe'] }).toString('utf8');

// The app's repository: its root, HEAD, and the one door every input read goes through (refusing uncommitted files).
function appRepo(dir) {
  let root;
  try { root = git(dir, 'rev-parse', '--show-toplevel').trim(); }
  catch (e) { refuse(`${dir} is not inside a git work tree; a page is built from an app's committed inputs`); }
  root = fs.realpathSync(root);
  const head = git(root, 'rev-parse', 'HEAD').trim();   // the full sha: an abbreviation's length varies by clone
  const out = git(root, 'status', '--porcelain=v1', '-z', '--untracked-files=all').split('\0');
  const dirty = [];
  for (let i = 0; i < out.length; i++) {
    const e = out[i];
    if (!e) continue;
    dirty.push(e.slice(3));
    if (/^[RC]/.test(e)) dirty.push(out[++i]);
  }
  const base = fs.realpathSync(dir);
  const inputs = new Set();   // every existing input path the build went through the door for, repo-relative
  const door = rel => {
    const abs = path.resolve(base, rel);
    const r = path.relative(root, abs).split(path.sep).join('/');
    if (r.startsWith('..')) refuse(`${rel} is outside the app's repository ${root}`);
    const hit = dirty.find(u => u === r || u.startsWith(r + '/'));
    if (hit) refuse(`${hit} is uncommitted${hit === r ? '' : ` (this build reads ${r}/)`}; the page is built from committed inputs only — commit it, or build another app`);
    if (fs.existsSync(abs)) inputs.add(r);
    return abs;
  };
  return { root, head, door, inputs, exists: rel => fs.existsSync(door(rel)), read: (rel, enc) => fs.readFileSync(door(rel), enc) };
}

const rewrite = (html, pairs) => (pairs || []).reduce((h, [from, to]) => {
  if (!h.includes(from)) refuse(`link rewrite target not present: ${from}`);
  return h.split(from).join(to);
}, html);
// anchors: [{match, href}] — the one <a> whose inner html contains `match` gets `href` (a relative href drops
// target/rel: it stays on this site). 0 or 2+ matches refuse.
function reanchor(html, anchors) {
  for (const { match, href } of anchors || []) {
    const hits = [...html.matchAll(/<a\b[^>]*>[\s\S]*?<\/a>/g)].filter(m => m[0].includes(match));
    if (hits.length !== 1) refuse(`anchor match "${match}" hits ${hits.length} anchors (needs exactly 1)`);
    let a = hits[0][0].replace(/ href="[^"]*"/, ` href="${href}"`);
    if (!/^https?:/.test(href)) a = a.replace(/ target="_blank"/, '').replace(/ rel="noopener"/, '');
    html = html.replace(hits[0][0], a);
  }
  return html;
}
const link = a => `<a href="${esc(a.href)}"${/^https?:/.test(a.href) ? ' target="_blank" rel="noopener"' : ''}${a.class ? ` class="${esc(a.class)}"` : ''}${a.style ? ` style="${esc(a.style)}"` : ''}>${a.html || esc(a.text)}</a>`;

/**
 * Assembles one page. opts.ground: a ground object (ground.mjs) for the quotation gate, or null (then spec.quotes, if
 * declared, names it). Returns { app, html, files: Map(relative path → Buffer), ground, inputs (the app-repo paths it
 * read, a directory for a directory it read whole), log }.
 */
export async function buildPage(specFile, opts = {}) {
  const app = path.basename(specFile, '.json');
  const dir = path.dirname(path.resolve(specFile));
  const repo = appRepo(dir);
  if (!repo.exists(`${app}.json`)) refuse(`no spec: ${specFile}`);
  const spec = normalizeSpec(JSON.parse(repo.read(`${app}.json`, 'utf8')), app);

  const partials = loadPartials();
  const css = tokensCss();
  assertTheme(partials, css);
  const columns = gridColumns(css);

  if (opts.ground && spec.quotes) refuse(`${app}.json declares quotes and a ground was passed too; one ground per build`);
  const ground = opts.ground || (spec.quotes === null ? null
    : spec.quotes.repo === '.' ? gitGround(repo.root, spec.quotes.commit) : githubGround(spec.quotes.repo, spec.quotes.commit));
  const lib = library(ground, `declare "quotes": {"repo", "commit"} in ${app}.json, or pass --ground`);

  // copy: the app's copy file, with the spec's title and description as the page.* overrides
  const file = spec.copy ? JSON.parse(repo.read(spec.copy, 'utf8')) : { schema: COPY_SCHEMA, slots: {} };
  for (const id of ['page.title', 'page.description']) if (file.slots && id in file.slots) refuse(`${spec.copy}: ${id} is the spec's ${id.split('.')[1]} today; set it there`);
  const copy = normalizeCopy({ ...file, slots: { ...(file.slots || {}), 'page.title': spec.title, 'page.description': spec.description } }, spec.copy || `${app}.json`);
  const used = new Set();
  const fill = markup => fillCopy(markup, copy, used);

  // the showcase roster: imported now, a failure raised only where a page needs it
  const rosterTry = await loadRoster(dir).then(v => ({ v }), err => ({ err }));
  let roster = null, stills = null;
  function needRoster() {
    if (roster) return roster;
    if (rosterTry.err) throw rosterTry.err;
    const { X, release } = rosterTry.v;
    const site = X.SHOWCASE_SITE;
    if ((app === site.app) !== (spec.self_host === site.origin)) {
      refuse(`${app}.json self_host ${JSON.stringify(spec.self_host)} vs the roster's SHOWCASE_SITE ${JSON.stringify(site)} (${release}): ` +
        (app === site.app ? `${app} is the showcase app, so its spec's self_host must be ${site.origin}` : `${app} is not ${site.app}, so its spec's self_host may not be ${site.origin}`));
    }
    stills = new Map(X.EXHIBITS.map(r => [r, stillName(X, r)]));
    const onDisk = repo.exists(STILLS_DIR) ? fs.readdirSync(repo.door(STILLS_DIR)).filter(f => f.endsWith('.png')) : [];
    for (const [r, name] of stills) {
      if (!r.still) continue;
      if (!onDisk.includes(name)) refuse(`roster row ${r.id} declares a still (tick ${r.still.tick}) but ${path.join(dir, STILLS_DIR, name)} does not exist — promote the instrument's capture there`);
      const pv = `${STILLS_DIR}/${name.replace(/\.png$/, '.provenance.json')}`;
      if (!repo.exists(pv)) refuse(`still ${name} has no provenance sidecar ${path.join(dir, pv)}`);
      if (JSON.parse(repo.read(pv, 'utf8')).sceneKey !== name.replace(/\.png$/, '')) refuse(`${path.join(dir, pv)} is not the provenance of ${name}`);
    }
    const declared = new Set([...stills].filter(([r]) => r.still).map(([, n]) => n));
    for (const f of onDisk) if (!declared.has(f)) refuse(`${path.join(dir, STILLS_DIR, f)} is a still no roster row declares (roster ${release})`);
    return (roster = rosterTry.v);
  }
  const throughLine = () => {
    const { X, release } = needRoster();
    const p = X.SHOWCASE_THROUGH_LINE;
    if (!Array.isArray(p) || !p.length) refuse(`roster unreadable: ${release} exports no SHOWCASE_THROUGH_LINE paragraph (the data-showcase-throughline marker is filled from it)`);
    if (!p.every(s => typeof s === 'string' && s.length)) refuse(`the roster's SHOWCASE_THROUGH_LINE (${release}) holds a non-string or empty segment; the through-line is plain text — the page has no link renderer`);
    return p.join('');
  };
  const renderExhibits = html => html.replace(/<div\b([^>]*)\bdata-exhibits\b([^>]*)>\s*<\/div>/g, (m, a, b) => {
    const { X } = needRoster();
    const tiles = X.EXHIBITS.map((r, index) => `    ${tileHtml(tileOf(r, { roster: X, app, index, columns, cta: copy['proof.tile.cta'] }))}`);
    used.add('proof.tile.cta');
    return `<div${a}data-exhibits${b}>\n${tiles.join('\n')}\n  </div>`;
  });
  const renderThroughLine = html => (spec.through_line === null ? html
    : html.replace(THROUGH_SLOT, (m, tag, attrs, inner) => (inner.trim() ? m : `<${tag}${attrs}>${esc(throughLine())}</${tag}>`)));
  const fillSlots = (html, f) => renderThroughLine(renderExhibits(lib.renderShelves(html, f)));
  const gate = (html, f) => lib.gateFragment(fillSlots(html, f), f);

  const fragment = f => {
    if (!repo.exists(f)) refuse(`fragment not found: ${f}`);
    return repo.read(f, 'utf8');
  };
  function navHtml() {
    if (spec.nav === 'template') {
      let nav = rewrite(fill(partials.nav), spec.links);
      if (spec.login) {
        const at = '</a>\n  </div>\n</div></nav>';
        if (!nav.includes(at)) refuse('theme nav: no place for the login button');
        nav = nav.replace(at, `</a>${fill(partials.login)}\n  </div>\n</div></nav>`);
      }
      return nav;
    }
    return `<nav class="nav"><div class="wrap">
  <a class="brand" href="#top"><b>${esc(spec.brand.name)}</b><span>${esc(spec.brand.tag)}</span></a>
  <div class="navlinks">
    ${spec.nav.map(link).join('')}
  </div>
</div></nav>`;
  }
  function heroHtml() {
    if (spec.hero === 'template') return rewrite(fill(partials.hero), spec.links);
    if (spec.hero.file) {
      const html = fragment(spec.hero.file);
      if (!/^\s*<header class="hero[^"]*" id="top">/.test(html)) refuse(`${spec.hero.file}: a hero fragment starts with <header class="hero…" id="top">`);
      return html;
    }
    const h = spec.hero;
    if (h.src) lib.assertHeld(h.src, h.h1_html, 'hero h1');
    return `<header class="hero" id="top">
  ${h.art ? `<div class="hero-art"><img src="${esc(h.art.src)}" alt="${esc(h.art.alt)}"></div>` : ''}
  <div class="wrap">
    <p class="eyebrow">${esc(h.eyebrow)}</p>
    <h1>${h.h1_html}</h1>
    <p class="lede">${h.lede_html || esc(h.lede)}</p>
    <div class="cta-row">
      ${link({ ...h.primary, class: 'btn btn-primary' })}
      ${h.secondary ? link({ ...h.secondary, class: 'btn btn-ghost' }) : ''}
    </div>
    ${h.kicker_html ? `<p class="kicker">${h.kicker_html}</p>` : ''}
  </div>
</header>`;
  }
  function footerHtml() {
    if (spec.footer === 'template') return rewrite(fill(partials.footer), spec.links);
    const f = spec.footer;
    return `<footer><div class="wrap">
  <div class="brand"><b>${esc(f.name)}</b><span>${esc(f.tag)}</span></div>
  <div class="row">
    ${f.links.map(link).join('')}
  </div>
  <p class="legal">${f.legal_html}</p>
</div></footer>`;
  }

  const heroOut = gate(heroHtml(), 'hero');
  const heroPlaced = spec.sections.some(s => s.hero === true);
  const bodySections = spec.sections.map(s => {
    if (s.hero === true) return heroOut;
    if (s.use) return fillSlots(reanchor(rewrite(rewrite(fill(sectionOf(partials, s.use)), spec.links), s.links), s.anchors), `theme section ${s.use}`);
    return gate(fragment(s.file), s.file);
  });

  // scripts
  const forwarder = () => {
    const f = spec.scripts.forward;
    if (!f) return '';
    // a #<path> (it has a slash or a dot; in-page anchors have neither) forwards to the viewer, on load and on any later hash change
    if (f.hash_to) return `<script>(function(){function f(){var h=location.hash;if(h.length>1&&/[\\/.]/.test(h))location.replace(${JSON.stringify(f.hash_to)}+h);}f();addEventListener('hashchange',f);})();</script>`;
    return `<script>if(location.search)location.replace(${JSON.stringify(f.query_to)}+location.search+location.hash);</script>`;
  };
  const sdk = spec.scripts.sdk ? await loadBridgeFile(dir) : null;
  const scripts = [spec.scripts.template_scripts ? partials.requestForm.trim() : '', spec.scripts.codesite ? CODESITE_SCRIPT : '',
    ...(spec.scripts.extra || []).map(f => { if (!repo.exists(f)) refuse(`script not found: ${f}`); return repo.read(f, 'utf8'); })].filter(Boolean);

  // head: the theme's, its CSS included, retitled through the copy, forwarder first
  let head = fill(partials.head).replace(TOKENS_INCLUDE, () => css);
  head = head.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n${forwarder()}`);
  if (spec.css) head = head.replace('</style>', () => `\n/* ${app} */\n${spec.css}\n</style>`);
  if (spec.login) {
    if (!head.includes('--cyan-ink:')) refuse('login button: the theme CSS has no --cyan-ink token');
    head = head.replace('</style>', () => `\n/* login */\n${partials.loginCss}\n</style>`);
  }
  if (spec.scripts.import_map) {
    const at = head.lastIndexOf('</head>');
    head = `${head.slice(0, at)}${IMPORT_MAP_BEGIN}\n${IMPORT_MAP_END}\n${head.slice(at)}`;
  }
  const footerOut = gate(footerHtml(), 'footer');
  const navOut = navHtml();
  const body = `

${navOut}

${(heroPlaced ? bodySections : [heroOut, ...bodySections]).join('\n\n')}

${footerOut}

${sdk ? `<script src="${sdk.name}"></script>\n` : ''}${scripts.map(s => `<script>\n${s}\n</script>`).join('\n')}${(spec.scripts.modules || []).map((m, i) => `${i || scripts.length ? '\n' : ''}<script type="module" src="${m}"></script>`).join('')}
</body>
</html>
`;
  // a page carrying a tile slot or a declared through-line marker is checked against the roster, filled or not
  if (body.search(EXHIBITS_MARK) >= 0 || (spec.through_line !== null && body.search(THROUGH_MARK) >= 0)) needRoster();
  const html = `${head}<body ${stampOf({ app, theme: THEME_VERSION, roster: roster && roster.version, build: repo.head })}>${body}`;

  // the copy layer's sweep: an override must land on this page; a quotation in an override is gated
  for (const id of overriddenOf(copy)) {
    if (!used.has(id)) refuse(`${spec.copy || `${app}.json`}: copy override ${id} has no marker on this page (its section is not used)`);
    if (slotKind(id) === 'html') lib.gateQuotes(copy[id], `copy ${id}`);
  }
  lib.sweepDeepLinks(html);
  assertPage(html, { app, theme: THEME_VERSION, build: repo.head, spec, copy, roster, columns });

  // images: what the page uses, from the theme, the stills home, the app dir or the ground
  const usedImages = new Set([...html.matchAll(new RegExp(`(?:src|href)="${IMAGES_OUT}/([^"]+)"`, 'g'))].map(m => m[1]));
  const extra = new Map(spec.images.map(i => [i.to.replace(new RegExp(`^${IMAGES_OUT}/`), ''), i.from]));
  const files = new Map();
  for (const name of usedImages) {
    const still = stills && [...stills.values()].includes(name);
    if (still && extra.has(name)) refuse(`spec declares image ${name}, which is a tile still; tile stills live only in ${STILLS_DIR}/`);
    let data;
    if (still) data = repo.read(`${STILLS_DIR}/${name}`);
    else if (extra.has(name)) {
      const from = extra.get(name);
      if (from.startsWith('frontpage:')) {
        const rel = from.slice('frontpage:'.length);
        if (!repo.exists(rel)) refuse(`image not found: ${path.join(dir, rel)}`);
        data = repo.read(rel);
      } else data = lib.read(from);
    } else {
      data = themeImage(name);
      if (!data) refuse(`image "${name}" is neither a theme image nor declared in the spec`);
    }
    files.set(`${IMAGES_OUT}/${name}`, data);
  }
  for (const name of extra.keys()) if (!usedImages.has(name)) refuse(`spec declares an unused image: ${name}`);
  files.set(PAGE_FILE, Buffer.from(html));
  if (spec.share) {
    const assets = repo.door(`${app}/share`);
    const { files: sf } = shareFiles(app, spec.share, await loadShareContract(dir), assets);
    for (const [k, v] of sf) files.set(k, v);
  }
  if (sdk) files.set(sdk.name, sdk.data);
  const log = `${app}: index.html (${Math.round(Buffer.byteLength(html) / 1024)} KB) from theme ${THEME_VERSION} at HEAD ${repo.head}; ${spec.sections.filter(s => !s.hero).length} sections${heroPlaced ? ' (hero placed among them)' : ''} (${spec.sections.filter(s => s.use).length} reused, ${spec.sections.filter(s => s.file).length} fragments), ${lib.state.gated} quotations gated, ${usedImages.size} images`;
  return { app, html, files, ground, inputs: [...repo.inputs].sort(), log };
}

export function writePage(result, out) {
  for (const [rel, data] of result.files) {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    fs.writeFileSync(path.join(out, rel), data);
  }
}

const USAGE = 'usage: egpt-site-theme build <dir>/<app>.json --out <dir> [--dry-run] [--ground <git checkout>@<commit> | --ground-github <owner/name>@<sha>]';
/** The CLI: returns the exit code; refusals print `ERROR: <message>`. */
export async function main(argv) {
  try {
    const [cmd, specFile, ...rest] = argv;
    if (cmd !== 'build' || !specFile || specFile.startsWith('--')) refuse(USAGE);
    const opt = n => { const i = rest.indexOf(n); if (i < 0) return null; if (!rest[i + 1] || rest[i + 1].startsWith('--')) refuse(`${n} needs a value; ${USAGE}`); return rest[i + 1]; };
    const known = ['--out', '--dry-run', '--ground', '--ground-github'];
    for (const a of rest) if (a.startsWith('--') && !known.includes(a)) refuse(`unknown option ${a}; ${USAGE}`);
    const dry = rest.includes('--dry-run');
    const out = opt('--out');
    if (!out && !dry) refuse(`--out <dir> is required (or --dry-run); ${USAGE}`);
    if (opt('--ground') && opt('--ground-github')) refuse('--ground and --ground-github are two grounds; pass one');
    let ground = null;
    if (opt('--ground')) {
      const m = /^(.*)@([^@/]+)$/.exec(opt('--ground'));
      if (!m) refuse(`--ground ${opt('--ground')}: a ground is <git checkout>@<commit>`);
      ground = gitGround(path.resolve(m[1]), m[2]);
    } else if (opt('--ground-github')) {
      const m = /^([\w.-]+\/[\w.-]+)@([0-9a-f]{40})$/.exec(opt('--ground-github'));
      if (!m) refuse(`--ground-github ${opt('--ground-github')}: a GitHub ground is <owner/name>@<full sha>`);
      ground = githubGround(m[1], m[2]);
    }
    const r = await buildPage(specFile, { ground });
    if (!dry) writePage(r, path.resolve(out));
    console.log(`${dry ? '[dry-run] ' : ''}${r.log}`);
    return 0;
  } catch (e) {
    console.error(`ERROR: ${e instanceof ThemeError ? e.message : (e && e.stack) || e}`);
    return 1;
  }
}
