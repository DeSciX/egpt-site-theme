// ./page — the page assembler and its CLI. buildPage(specFile, opts) assembles one app's front page from the theme
// (./partials, ./tokens.css, ./copy) and the app's inputs, all read from the app's git repository AT HEAD:
//
//   <dir>/<app>.json              the spec (spec.mjs SPEC_KEYS), the app id is its file name
//   <dir>/<fragment>              the files its sections, hero and scripts name
//   <dir>/exhibits/<sceneKey>.png the tile stills (+ .provenance.json), one per roster row that declares a still
//   <dir>/<app>/share/            the rendered share images, when the spec has a share block
//
// An input that is uncommitted refuses (the page is built from committed inputs only). The tiles and through-line are
// the pinned showcase roster's (./tiles); quotations and library deep links are checked against the quotation ground
// (ground.mjs, library.mjs). Every page passes ./gates assertPage before it is returned.
//
//   egpt-site-theme build <dir>/<app>.json --out <dir> [--dry-run] [--ground <git checkout>@<commit> | --ground-github <owner/name>@<sha>]
